# Problema: "Quatro vezes um número subtraído de 8 é igual a 28."
#
# Equação:
# 4x - 8 = 28
#
# Resolvendo:
# 4x = 28 + 8
# 4x = 36
# x = 36 / 4
# x = 9

numero = (28 + 8) / 4

# Verificando a condição
resultado = (4 * numero) - 8

print(f"Número procurado: {numero}")
print(f"Verificação: 4 x {numero} - 8 = {resultado}")
print(f"A resposta está correta? {resultado == 28}")
