# Exercício: um número somado ao seu dobro resulta em 36.
#
# Montando a equação:
# x + 2x = 36
# 3x = 36
# x = 36 / 3 = 12

x = 12
dobro = 2 * x
resultado = x + dobro

print(f"Número: {x}")
print(f"Dobro do número: {dobro}")
print(f"Soma: {resultado}")
print(f"A resposta está correta? {resultado == 36}")