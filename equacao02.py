'''
“A diferença entre um número e sua terça parte é 20.”
Qual é esse número?

'''

# A diferença entre um número e sua terça parte é 20.
# x - (x / 3) = 20
# (3x - x) / 3 = 20
# 2x / 3 = 20
# 2x = 60
# x = 30

x = 30
terca_parte = x / 3
resultado = x - terca_parte

print(f"O numero e: {x}.")
print(f"A terca parte e: {terca_parte}.")
print(f"A diferenca entre {x} e {terca_parte} e: {resultado}.")

# O resultado mostra que o número é 30, porque sua terça parte é 10.
# A diferença entre 30 e 10 é 20, que coincide com o enunciado.
# Em termos matemáticos: 30 - 30/3 = 30 - 10 = 20.

