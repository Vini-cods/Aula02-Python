# Problema: "Multiplique um número por 3 e subtraia 9. O resultado é igual ao próprio número."
# Equação: 3x - 9 = x

# Resolvendo a equação:
# 3x - x = 9
# 2x = 9
# x = 9 / 2
# x = 4.5

numero = 4.5

#Realizando a operação descrita no problema

resultado = (3 * numero) - 9

print(f"O numero procurado e {numero}.")
print(f"Verificacao: (3 * {numero}) - 9 = {resultado}.")
print(f"O resultado ({resultado}) e igual ao numero original ({numero}).")

# O número é 4.5 porque ao substituir na equação 3x - 9 = x temos:
# 3x - x = 9 → 2x = 9 → x = 9/2 = 4.5.
# Ao calcular (3 * 4.5) - 9 obtemos 13.5 - 9 = 4.5, que confirma que o resultado é
# igual ao número original, portanto a solução está correta.


