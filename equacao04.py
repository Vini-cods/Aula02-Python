'''Multiplique um número por 3 e subtraia 9.
O resultado é igual ao próprio número.'''

# Problema: "Multiplique um número por 3 e subtraia 9. O resultado é igual ao próprio número."
# Equação: 3x - 9 = x

# Resolvendo a equação:
# 3x - x = 9
# 2x = 9
# x = 9 / 2
# x = 4.5

numero = 9 / 2

#Realizando a operação descrita no problema

resultado = (3 * numero) - 9

print(f"Número procurado: {numero}")
print(f"Resultado de 3x - 9: {resultado}")
print(f"A resposta está correta? {resultado == numero}")


